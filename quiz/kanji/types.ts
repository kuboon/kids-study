/**
 * 漢字出題の基盤データ型。
 *
 * 「漢字 → 読みの一覧」という辞書的な構造ではなく、**語**を単位にする。
 * 辞書から機械的にプロンプトを作ると、
 *   - 読みだけでは漢字が一意に定まらない（[き] → 木/汽/期/季/規/樹…）
 *   - 小学校で習わない読みが混ざる（奈 → いかん、縄 → ただす…）
 * という2つの欠陥が構造的に避けられない。「その読みが漢字を一意に決めるか」
 * 「小学生が知っている語か」は辞書に書かれていない編集判断だからである。
 *
 * そこで語データは人が書き、コードは*検証*に徹する（words_test.ts が
 * 一意性・読みの妥当性・文脈のかな縛り・学年網羅を機械的に保証する）。
 *
 * 1つの語が2つのゲームの出題を兼ねる:
 *   書き取り: `pre + [read] + post` を見せて target を書かせる  てん[き] → 気
 *   読み4択:  `pre + [target] + post` を見せて read を選ばせる   てん[気] → き
 */

export type KanjiWord = {
  /** 出題対象の漢字1字。これを書く／読む。 */
  target: string;
  /** target の読み（ひらがな）。連濁・促音は語形のまま書く（学校 → がっ）。 */
  read: string;
  /** target より前の部分。かなのみ（既習漢字に依存させないため）。 */
  pre?: string;
  /** target より後の部分。送り仮名や熟語の後半。かなのみ。 */
  post?: string;
};

/** 書き取りの出題文。読みを [] で囲み、その漢字を書かせる。 */
export const displayWrite = (w: KanjiWord): string =>
  `${w.pre ?? ""}[${w.read}]${w.post ?? ""}`;

/** 読み4択の出題文。漢字を [] で囲み、その読みを選ばせる。 */
export const displayRead = (w: KanjiWord): string =>
  `${w.pre ?? ""}[${w.target}]${w.post ?? ""}`;

/** 読み4択の正解。送り仮名まで含めて答えさせる（[およ]ぐ → およぐ）。 */
export const answerRead = (w: KanjiWord): string => `${w.read}${w.post ?? ""}`;
